// Функція формування (введення) динамічного масиву структур з контролем помилок
void Create(Student* p, const int N)
{
    int ispec;                  // тимчасова цілочисельна змінна для вибору спеціальності
    for (int i = 0; i < N; i++)
    {
        cout << "Студент № " << i + 1 << ":" << endl;

        cin.get();              // очищуємо буфер клавіатури — бо залишаються символи
        cin.sync();             // "кінець рядка", які не дають ввести наступний літерний рядок

        cout << "    прізвище: "; getline(cin, p[i].prizv);

        // Введення курсу з контролем діапазону [1..6]
        do {
            cout << "    курс (1-6): ";
            cin >> p[i].kurs;
            if (cin.fail() || p[i].kurs < 1 || p[i].kurs > 6) {
                cin.clear();
                cin.ignore((numeric_limits<streamsize>::max)(), '\n');
                cout << "    Помилка! Введіть курс від 1 до 6." << endl;
                p[i].kurs = 0;
            }
        } while (p[i].kurs < 1 || p[i].kurs > 6);

        // Введення спеціальності з контролем діапазону [0..4]
        do {
            cout << "    спеціальність (0 - Комп. науки, 1 - Інформатика, 2 - Мат. та екон., 3 - Фіз. та інформ., 4 - Труд. навч.): ";
            cin >> ispec;
            if (cin.fail() || ispec < 0 || ispec > 4) {
                cin.clear();
                cin.ignore((numeric_limits<streamsize>::max)(), '\n');
                cout << "    Помилка! Введіть число від 0 до 4." << endl;
                ispec = -1;
            }
        } while (ispec < 0 || ispec > 4);
        p[i].spec = (Specialnist)ispec; // приведення цілого числа до переліку Specialnist

        // Введення оцінки з фізики з контролем [1..5]
        do {
            cout << "    оцінка з фізики (1-5): ";
            cin >> p[i].fizyka;
            if (cin.fail() || p[i].fizyka < 1 || p[i].fizyka > 5) {
                cin.clear();
                cin.ignore((numeric_limits<streamsize>::max)(), '\n');
                cout << "    Помилка! Введіть оцінку від 1 до 5." << endl;
                p[i].fizyka = 0;
            }
        } while (p[i].fizyka < 1 || p[i].fizyka > 5);

        // Введення оцінки з математики з контролем [1..5]
        do {
            cout << "    оцінка з математики (1-5): ";
            cin >> p[i].matematika;
            if (cin.fail() || p[i].matematika < 1 || p[i].matematika > 5) {
                cin.clear();
                cin.ignore((numeric_limits<streamsize>::max)(), '\n');
                cout << "    Помилка! Введіть оцінку від 1 до 5." << endl;
                p[i].matematika = 0;
            }
        } while (p[i].matematika < 1 || p[i].matematika > 5);

        // Введення оцінки з інформатики з контролем [1..5]
        do {
            cout << "    оцінка з інформатики (1-5): ";
            cin >> p[i].informatika;
            if (cin.fail() || p[i].informatika < 1 || p[i].informatika > 5) {
                cin.clear();
                cin.ignore((numeric_limits<streamsize>::max)(), '\n');
                cout << "    Помилка! Введіть оцінку від 1 до 5." << endl;
                p[i].informatika = 0;
            }
        } while (p[i].informatika < 1 || p[i].informatika > 5);

        cout << endl;
    }
}

// Допоміжна функція для обчислення індивідуального середнього балу студента
double AverageGrade(const Student& s)
{
    // Ділимо на дійсне число 3.0 для отримання точного дійсного результату
    return (s.fizyka + s.matematika + s.informatika) / 3.0;
}

// Функція виведення масиву структур у вигляді таблиці з 7 клітинок (згідно з Рівнем А)
void Print(Student* p, const int N)
{
    cout << "==================================================================================" << endl;
    cout << "|  №  |   Прізвище   | Курс |  Спеціальність  | Фізика | Математика | Інформатика |" << endl;
    cout << "----------------------------------------------------------------------------------" << endl;

    for (int i = 0; i < N; i++)
    {
        cout << "| " << setw(3) << right << i + 1 << " ";
        cout << "| " << setw(13) << left << p[i].prizv
             << "| " << setw(4) << right << p[i].kurs << " "
             << "| " << setw(16) << left << specStr[p[i].spec]
             << "| " << setw(6) << right << p[i].fizyka << " "
             << "| " << setw(10) << right << p[i].matematika << " "
             << "| " << setw(11) << right << p[i].informatika << " |" << endl;
    }
    cout << "==================================================================================" << endl;
    cout << endl;
}

// Варіант 16, завдання 1:
// Послідовний перегляд масиву та підрахунок студентів із середнім балом > 4,5
int CountHighAverage(Student* p, const int N)
{
    int k = 0;                  // лічильник студентів, що відповідають умові
    for (int i = 0; i < N; i++)
    {
        if (AverageGrade(p[i]) > 4.5)
        {
            k++;
        }
    }
    return k;                   // повертаємо результат у місце виклику
}

// Варіант 16, завдання 2:
// Порівнюючи середні бали для кожного предмета, повертаємо назву предмета з найбільшим середнім балом
string BestSubject(Student* p, const int N)
{
    if (N <= 0) return "Немає даних";

    double sumFiz = 0.0;        // сума оцінок з фізики по групі
    double sumMat = 0.0;        // сума оцінок з математики по групі
    double sumInf = 0.0;        // сума оцінок з інформатики по групі

    // Накопичуємо суми оцінок по кожному предмету
    for (int i = 0; i < N; i++)
    {
        sumFiz += p[i].fizyka;
        sumMat += p[i].matematika;
        sumInf += p[i].informatika;
    }

    // Обчислюємо середній бал кожного предмета по групі
    double avgFiz = sumFiz / N;
    double avgMat = sumMat / N;
    double avgInf = sumInf / N;

    // Послідовно визначаємо максимум та повертаємо назву відповідного предмета
    double maxAvg = avgFiz;
    string bestName = "Фізика";

    if (avgMat > maxAvg) {
        maxAvg = avgMat;
        bestName = "Математика";
    }
    if (avgInf > maxAvg) {
        maxAvg = avgInf;
        bestName = "Інформатика";
    }

    return bestName;
}
