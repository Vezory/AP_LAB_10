// Функція формування (введення) динамічного масиву структур
void Create(Student* p, const int N) {
    int ispec; // допоміжна змінна для зчитування номера спеціальності
    for (int i = 0; i < N; i++) {
        cout << "Студент № " << i + 1 << ":" << endl;

        // Очищення буфера клавіатури від залишкових символів переходу на новий рядок ('\n'),
        // які залишаються після попередніх cin >> і заважають роботі getline
        cin.get();
        cin.sync();

        cout << "  прізвище: "; 
        getline(cin, p[i].prizv); // зчитування повного рядка з пробілами

        cout << "  курс: "; 
        cin >> p[i].kurs;

        cout << "  спеціальність (0 - Комп. науки, 1 - Інформатика, 2 - Мат. та екон., 3 - Фіз. та інформ., 4 - Труд. навч.): ";
        cin >> ispec;
        p[i].spec = (Specialnist)ispec; // приведення цілого числа до типу переліку Specialnist

        cout << "  оцінка з фізики: "; 
        cin >> p[i].fizyka;

        cout << "  оцінка з математики: "; 
        cin >> p[i].matematika;

        cout << "  оцінка з інформатики: "; 
        cin >> p[i].informatika;

        cout << endl;
    }
}

// Допоміжна функція для обчислення індивідуального середнього балу студента
double AverageGrade(const Student& s) {
    // Середній бал обчислюється як дійсне число (ділення на 3.0, а не на 3)
    return (s.fizyka + s.matematika + s.informatika) / 3.0;
}

// Функція виведення масиву структур у вигляді форматованої таблиці (7 клітинок)
void Print(const Student* p, const int N) {
    // Друк заголовка та шапки таблиці відповідно до зразка посібника
    cout << "==========================================================================================" << endl;
    cout << "| № |   Прізвище   | Курс |  Спеціальність  | Фізика | Математика | Інформатика | Сер. бал |" << endl;
    cout << "------------------------------------------------------------------------------------------" << endl;

    // Порядковий вивід кожного елемента масиву
    for (int i = 0; i < N; i++) {
        double avg = AverageGrade(p[i]); // обчислюємо середній бал конкретного студента
        cout << "| " << setw(1) << right << i + 1 << " "
             << "| " << setw(12) << left << p[i].prizv << " "
             << "| " << setw(4) << right << p[i].kurs << " "
             << "| " << setw(15) << left << specStr[p[i].spec] << " "
             << "| " << setw(6) << right << p[i].fizyka << " "
             << "| " << setw(10) << right << p[i].matematika << " "
             << "| " << setw(11) << right << p[i].informatika << " "
             << "| " << setw(8) << fixed << setprecision(2) << right << avg << " |" << endl;
    }
    cout << "==========================================================================================" << endl;
}

// Варіант 16. Завдання 1:
// Функція повертає кількість студентів, чий середній бал вищий за 4.5
int CountHighAverage(const Student* p, const int N) {
    int count = 0; // лічильник студентів, що відповідають умові
    for (int i = 0; i < N; i++) {
        // Якщо середній бал студента строго більший ніж 4.5
        if (AverageGrade(p[i]) > 4.5) {
            count++;
        }
    }
    return count; // повертаємо знайдену кількість
}

// Варіант 16. Завдання 2:
// Функція порівнює середні бали для кожного з 3-х предметів по всій групі
// та повертає назву предмета, середній бал якого є найбільшим
string BestSubject(const Student* p, const int N) {
    if (N <= 0) return "Немає даних";

    double sumFiz = 0.0; // накопичувач суми оцінок з фізики
    double sumMat = 0.0; // накопичувач суми оцінок з математики
    double sumInf = 0.0; // накопичувач суми оцінок з інформатики

    // Підсумовуємо всі оцінки з кожного предмета
    for (int i = 0; i < N; i++) {
        sumFiz += p[i].fizyka;
        sumMat += p[i].matematika;
        sumInf += p[i].informatika;
    }

    // Обчислюємо середній бал групи з кожного предмета
    double avgFiz = sumFiz / N;
    double avgMat = sumMat / N;
    double avgInf = sumInf / N;

    // Порівнюємо середні бали між собою і повертаємо назву найкращого предмета
    if (avgFiz >= avgMat && avgFiz >= avgInf) {
        return "Фізика";
    } else if (avgMat >= avgFiz && avgMat >= avgInf) {
        return "Математика";
    } else {
        return "Інформатика";
    }
}
