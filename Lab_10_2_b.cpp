// Допоміжна функція для отримання значення 3-ї профільної оцінки з об'єднання (union)
// залежно від спеціальності студента
int GetThirdGrade(const Student& s) {
    switch (s.spec) {
    case KN: 
        return s.programuvannya;  // для Комп'ютерних наук — оцінка з програмування
    case INF: 
        return s.chyselni_metody; // для Інформатики — оцінка з чисельних методів
    default: 
        return s.pedagogika;      // для решти спеціальностей — оцінка з педагогіки
    }
}

// Допоміжна функція для обчислення індивідуального середнього арифметичного балу
double AverageGrade(const Student& s) {
    // Сума трьох дисциплін ділиться на дійсне 3.0
    return (s.fizyka + s.matematika + GetThirdGrade(s)) / 3.0;
}

// Функція формування (введення) динамічного масиву структур
