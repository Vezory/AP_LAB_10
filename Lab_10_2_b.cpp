// 1. ФІЗИЧНЕ СОРТУВАННЯ (Варіант 16, Рівень В):
// Багаторівневе сортування методом бульбашки:
// 1-ша черга: за середнім балом (за зростанням);
// 2-га черга: за оцінкою з 3-го предмета (значення з union через GetThirdGrade);
// 3-тя черга: за прізвищем у спадному порядку (зворотний алфавітний порядок).
// ----------------------------------------------------------------------------
void Sort(Student* p, const int N) {
    Student tmp; // тимчасова змінна для обміну двох структур у пам'яті
    for (int i0 = 0; i0 < N - 1; i0++) {
        for (int i1 = 0; i1 < N - i0 - 1; i1++) {
            double avg1 = AverageGrade(p[i1]);
            double avg2 = AverageGrade(p[i1 + 1]);
            int g3_1 = GetThirdGrade(p[i1]);
            int g3_2 = GetThirdGrade(p[i1 + 1]);

            // Перевірка умов сортування Варіанту 16 для Рівня В:
            if ((avg1 > avg2) ||
                (avg1 == avg2 && g3_1 > g3_2) ||
                (avg1 == avg2 && g3_1 == g3_2 && p[i1].prizv < p[i1 + 1].prizv)) {
                // Фізичний обмін структур у масиві
                tmp = p[i1];
                p[i1] = p[i1 + 1];
                p[i1 + 1] = tmp;
            }
        }
    }
}

// ----------------------------------------------------------------------------
// 2. ІНДЕКСНЕ СОРТУВАННЯ (Варіант 16, Рівень В):
// Створює масив індексів I[0..N-1] та сортує його без фізичного копіювання даних:
// 1-ша черга: за середнім балом;
// 2-га черга: за оцінкою з 3-го предмета (union);
// 3-тя черга: за прізвищем за алфавітом (прямий порядок).
// ----------------------------------------------------------------------------
int* IndexSort(const Student* p, const int N) {
    // Виділення динамічного масиву індексів
    int* I = new int[N];
    for (int i = 0; i < N; i++) {
        I[i] = i; // початкове заповнення природними індексами
    }

    int tmp; // змінна для перестановки індексів
    for (int i0 = 0; i0 < N - 1; i0++) {
        for (int i1 = 0; i1 < N - i0 - 1; i1++) {
            double avg1 = AverageGrade(p[I[i1]]);
            double avg2 = AverageGrade(p[I[i1 + 1]]);
            int g3_1 = GetThirdGrade(p[I[i1]]);
            int g3_2 = GetThirdGrade(p[I[i1 + 1]]);

            // Критерії впорядкування індексів (3-тя черга — прямий алфавітний порядок prizv > prizv):
            if ((avg1 > avg2) ||
                (avg1 == avg2 && g3_1 > g3_2) ||
                (avg1 == avg2 && g3_1 == g3_2 && p[I[i1]].prizv > p[I[i1 + 1]].prizv)) {
                // Обмінюємо тільки значення індексів у масиві I
                tmp = I[i1];
                I[i1] = I[i1 + 1];
                I[i1 + 1] = tmp;
            }
        }
    }
    return I; // повернення покажчика на масив впорядкованих індексів
}

