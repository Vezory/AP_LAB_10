// ----------------------------------------------------------------------------
// 3. БІНАРНИЙ ПОШУК (Варіант 16, Рівень В):
// Шукає студента у фізично впорядкованому масиві за складеним ключем:
// (середній бал, оцінка з 3-го предмета через GetThirdGrade, прізвище)
// Повертає індекс або -1 при відсутності. Часова складність: O(log N).
// ----------------------------------------------------------------------------
int BinSearch(const Student* p, const int N, const string prizv, const double avg, const int thirdGrade) {
    int L = 0;        // ліва межа діапазону пошуку
    int R = N - 1;    // права межа діапазону пошуку
    int m;            // середина поточного діапазону

    while (L <= R) {
        m = (L + R) / 2;
        double curAvg = AverageGrade(p[m]);
        int curThird = GetThirdGrade(p[m]);

        // 1. Точний збіг усіх складових ключа пошуку
        if (curAvg == avg && curThird == thirdGrade && p[m].prizv == prizv) {
            return m; // знайдено!
        }

        // 2. Порівняння відповідно до критерію фізичного сортування (Варіант 16)
        if ((curAvg < avg) ||
            (curAvg == avg && curThird < thirdGrade) ||
            (curAvg == avg && curThird == thirdGrade && p[m].prizv > prizv)) {
            L = m + 1; // переміщення лівої межі праворуч
        } else {
            R = m - 1; // переміщення правої межі ліворуч
        }
    }
    return -1; // не знайдено
}
