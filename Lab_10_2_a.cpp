// 2. ІНДЕКСНЕ СОРТУВАННЯ (Варіант 16):
// Впорядкування масиву покажчиків/індексів I без зміни розташування елементів у вихідному масиві структур:
// 1-ша черга: за середнім балом (за зростанням);
// 2-га черга: при однакових середніх балах — за оцінкою з 3-го предмета (інформатики);
// 3-тя черга: при однакових балах та оцінках — за прізвищем в прямому алфавітному порядку.
// ----------------------------------------------------------------------------
int* IndexSort(const Student* p, const int N) {
    // Виділення динамічної пам'яті під масив цілих чисел (індексів)
    int* I = new int[N];
    // Початкова ініціалізація індексного масиву: I[0]=0, I[1]=1, ..., I[N-1]=N-1
    for (int i = 0; i < N; i++) {
        I[i] = i;
    }

    int tmp; // проміжна змінна для обміну індексів
    for (int i0 = 0; i0 < N - 1; i0++) {
        for (int i1 = 0; i1 < N - i0 - 1; i1++) {
            // Порівнюємо елементи структури, адресовані через поточні індекси I[i1] та I[i1+1]
            double avg1 = AverageGrade(p[I[i1]]);
            double avg2 = AverageGrade(p[I[i1 + 1]]);

            // Критерії сортування для індексного масиву (3-тя черга — прямий алфавітний порядок prizv > prizv):
            if ((avg1 > avg2) ||
                (avg1 == avg2 && p[I[i1]].informatika > p[I[i1 + 1]].informatika) ||
                (avg1 == avg2 && p[I[i1]].informatika == p[I[i1 + 1]].informatika && p[I[i1]].prizv > p[I[i1 + 1]].prizv)) {
                // Обмінюються лише цілі числа — індекси в масиві I, самі структури Student не переміщуються!
                tmp = I[i1];
                I[i1] = I[i1 + 1];
                I[i1 + 1] = tmp;
            }
        }
    }
    return I; // повернення покажчика на сформований масив індексів
}

