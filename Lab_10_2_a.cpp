// ----------------------------------------------------------------------------
// 3. БІНАРНИЙ (ДВІЙКОВИЙ) ПОШУК (Варіант 16):
// Працює виключно у фізично впорядкованому масиві за складним ключем:
// (середній бал, оцінка з 3-го предмета, прізвище)
// Повертає індекс знайденого елемента або -1, якщо елемент відсутній.
// Часова складність алгоритму: O(log N).
// ----------------------------------------------------------------------------
int BinSearch(const Student* p, const int N, const string prizv, const double avg, const int thirdGrade) {
    int L = 0;        // ліва межа простору пошуку
    int R = N - 1;    // права межа простору пошуку
    int m;            // індекс середнього елемента поточного діапазону

    while (L <= R) {
        m = (L + R) / 2; // обчислення індексу середини відрізка [L, R]
        double curAvg = AverageGrade(p[m]);

        // 1. Повна відповідність усім трьом критеріям пошуку
        if (curAvg == avg && p[m].informatika == thirdGrade && p[m].prizv == prizv) {
            return m; // елемент знайдено, повертаємо його позицію у масиві
        }

        // 2. Порівняння шуканого ключа з поточним елементом p[m] відповідно до порядку фізичного сортування:
        // Якщо поточний елемент "менший" за шуканий, зсуваємо ліву межу L вправо (L = m + 1)
        if ((curAvg < avg) ||
            (curAvg == avg && p[m].informatika < thirdGrade) ||
            (curAvg == avg && p[m].informatika == thirdGrade && p[m].prizv > prizv)) {
            L = m + 1;
        } else {
            // Інакше зсуваємо праву межу R вліво (R = m - 1)
            R = m - 1;
        }
    }
    return -1; // шуканого студента у масиві не знайдено
}
