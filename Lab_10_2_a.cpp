// Допоміжна функція для обчислення середнього арифметичного бала студента
double AverageGrade(const Student& s) {
    // Ділення на дійсне число 3.0 для отримання дробового значення середнього балу
    return (s.fizyka + s.matematika + s.informatika) / 3.0;
}

