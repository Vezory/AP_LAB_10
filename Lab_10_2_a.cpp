// 1. ФІЗИЧНЕ СОРТУВАННЯ (Варіант 16):
// Багаторівневе впорядкування масиву методом модифікованого обміну (бульбашки):
// 1-ша черга: за середнім балом (за зростанням);
// 2-га черга: при однакових середніх балах — за оцінкою з 3-го предмета (інформатики за зростанням);
// 3-тя черга: при однакових середніх балах та оцінках — за прізвищем у спадному порядку (зворотно до алфавіту).
// ----------------------------------------------------------------------------
void Sort(Student* p, const int N) {
    Student tmp; // проміжна змінна структури для обміну елементів у пам'яті
    for (int i0 = 0; i0 < N - 1; i0++) {
        for (int i1 = 0; i1 < N - i0 - 1; i1++) {
            // Обчислення середніх балів двох сусідніх студентів для порівняння
            double avg1 = AverageGrade(p[i1]);
            double avg2 = AverageGrade(p[i1 + 1]);

            // Перевірка складеної умови сортування Варіанту 16:
            // 1. Якщо середній бал лівого більший за правий -> міняємо місцями
            // 2. Якщо середні бали рівні, але оцінка з інформатики лівого більша -> міняємо
            // 3. Якщо і бали, і оцінки рівні, але прізвище лівого менше за правий (зворотний алфавітний порядок) -> міняємо
            if ((avg1 > avg2) ||
                (avg1 == avg2 && p[i1].informatika > p[i1 + 1].informatika) ||
                (avg1 == avg2 && p[i1].informatika == p[i1 + 1].informatika && p[i1].prizv < p[i1 + 1].prizv)) {
                // Фізичний обмін значень двох структур у пам'яті
                tmp = p[i1];
                p[i1] = p[i1 + 1];
                p[i1 + 1] = tmp;
            }
        }
    }
}

